'use strict';
const assert=require('node:assert/strict'),U=require('../ui/state.js');
assert.deepEqual(U.preferences(),U.defaults);
assert.equal(U.preferences({widgetEnabled:'true',theme:'bad',autoClosePanel:false}).widgetEnabled,false);
assert.equal(U.activity(null,{enabled:true,job:{active:false,status:'complete'}},{enabled:true,status:'idle'}).icon,'idle');
for(const status of ['queued','running','download_pending','download_starting'])assert(U.running({active:true,status}),status);
for(const status of ['completed','complete','permission_required','error','cooldown','retry_wait','waiting_for_tab','download_failed','completed_not_saved'])assert(!U.running({active:true,status}),status);
assert.equal(U.activity(null,{job:{active:true,status:'running'}},null).icon,'running');
assert.equal(U.activity({active:true,status:'permission_required'},null,null).icon,'base');
assert.equal(U.activity(null,null,{enabled:true,status:'running'}).icon,'running');
const canceled={active:true,status:'download_failed',message:'Browser download interrupted: USER_CANCELED. Staged bytes retained.'};
assert(U.userCanceledDownload(canceled));assert.equal(U.activity(canceled,null,{enabled:true,status:'idle'}).label,'Idle - monitoring enabled');
assert.equal(U.humanStatus(canceled),'Download canceled by user');
const terminalCanceled={active:false,destination:'download',status:'completed_not_saved',deliveryOutcome:'user_cancelled_save'};
assert(U.userCanceledDownload(terminalCanceled));
assert.equal(U.humanStatus(terminalCanceled),'Prepared, not saved (user canceled)');
assert.equal(U.activity(terminalCanceled,null,{enabled:true,status:'idle'}).icon,'idle');
assert.equal(U.activity({active:true,status:'download_failed',message:'Server timeout'},null,null).icon,'base');
assert.deepEqual(U.selection(['a','b'],new Set(['b'])),{count:1,checked:false,mixed:true});
assert.deepEqual(U.selection([],new Set()),{count:0,checked:false,mixed:false});
console.log('PASS: presentation-only status, canceled Save neutrality, preferences and tri-state selection');
