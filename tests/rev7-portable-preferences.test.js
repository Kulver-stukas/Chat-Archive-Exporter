'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const {createLibraryEnvironment}=require('./library-job-fixtures');
const load=e=>{vm.runInContext(fs.readFileSync(__dirname+'/../lib/portable-preferences.js','utf8'),e.box);return e.box.CAEPortablePreferences;};
(async()=>{
  const old=createLibraryEnvironment();old.rootRows=[old.node(1)];await old.start(true);
  const baseline=await old.drainLib();assert.equal(baseline.job.status,'complete');assert.equal(baseline.enabled,true);
  const V=old.box.ChatArchiveVault,p=old.prefix;
  const chat={enabled:true,scope:'workspace',enrollment:'tracked_and_new',sources:true};
  await V.writeFile(old.root,p+'/.sync.json',JSON.stringify({schema:'cae.background-config.v1',account_id:old.account,...chat,started_at:'2026-11-10T00:00:00Z'}));
  const pref=load(old),exports={...old.box.ChatArchiveExportSelection.DEFAULTS,thinking:false};
  const before=await pref.read(old.root,old.account,'Fallback display');
  assert.equal(before.chat.enabled,true);assert.equal(before.chat.scope,'workspace');assert.equal(before.hasInventory,true);
  assert.equal(await V.lookupFile(old.root,p+'/.preferences.json'),null,'reading never writes settings');
  await pref.write(old.root,old.account,'Fallback display',{chat,library:{enabled:true,monitorOnStart:false},export:exports,permission:'granted',token:'must-not-copy',queue:[1]});
  const disk=JSON.parse(await old.read(p+'/.preferences.json'));
  assert.equal(disk.library.monitorOnStart,false);assert.equal(disk.export.thinking,false);
  assert(!('permission' in disk)&&!('token' in disk)&&!('queue' in disk));
  const fresh=createLibraryEnvironment();const freshPref=load(fresh);
  await fresh.LS.bind(fresh.account,old.root);
  const saved=await freshPref.read(old.root,fresh.account,'Changed display');
  assert.equal(saved.chat.sources,true);assert.equal(saved.library.enabled,true);assert.equal(saved.hasInventory,true);
  await fresh.L.startup();await fresh.L.tick();
  assert.equal(await fresh.L.inspect(fresh.account),null);assert.equal(fresh.libCalls.length,0,'no monitoring on read or startup');
  const o={accountId:fresh.account,display:'Changed display',tabId:1,enabled:true};
  const restored=await fresh.L.restore(o);
  assert.equal(restored.enabled,true);assert.equal(restored.baseline_at,baseline.baseline_at);
  assert.equal(restored.catalog.items.length,baseline.catalog.items.length);
  assert(!fresh.libCalls.some(x=>x.type!=='CAE_STATUS'),'restore does not inventory or download originals');
  const other=createLibraryEnvironment();await other.LS.bind(other.account,old.root);
  other.scopeAccount='other-workspace';await assert.rejects(other.L.restore(o),/authenticated ChatGPT tab/);
  assert.equal(await other.L.inspect(other.account),null);
  await V.writeFile(old.root,p+'/.preferences.json',JSON.stringify({...disk,account_id:'other-workspace'}));
  await assert.rejects(pref.read(old.root,old.account,'Fallback display'),/Invalid workspace preferences/);
  await assert.rejects(pref.write(old.root,old.account,'Fallback display',{chat}),/Invalid workspace preferences/);
  console.log('PASS: portable preference allowlist, legacy sync settings, read-only recovery, explicit Library restore, baseline retention and foreign-workspace rejection');
})().catch(e=>{console.error(e);process.exitCode=1;});
