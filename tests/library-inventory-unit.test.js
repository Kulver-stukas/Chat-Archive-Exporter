'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const sandbox={window:{},URL,Map,Set};vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.resolve(__dirname,'../providers/chatgpt/library-inventory.js'),'utf8'),sandbox);
const I=sandbox.window.ChatArchiveLibraryInventory;
const file='file_00000000abcdef000000001111111111';
assert.equal(I.fileFromGallery({id:'s_hello',url:'https://chatgpt.com/backend-api/estuary/content?id='+file+'&sig=PRIVATE'}),file);
assert.equal(I.fileFromGallery({id:'s_hello',url:'https://bad.example/backend-api/estuary/content?id='+file}),null);
assert.equal(I.fileFromGallery({id:'s_hello',url:'https://chatgpt.com/backend-api/estuary/content?id=s_hello'}),null);
const nodes=[I.fromNode({id:'libfile_abc1234567890',file_id:file,kind:'file',name:'script.js',mime_type:'text/plain',parent_directory_id:'libdir_x',origination_thread_id:'chat_id'})];
const details=new Map([[file,I.fromDetail({metadata:{source_ip:'PRIVATE-IP', owner_id:'PRIVATE'},use_case:'my_files'})]]);
let cat=I.buildCatalog(nodes,[],details);
assert.equal(cat.items[0].format_class,'code');
assert.equal(cat.items[0].origin,'uploaded');assert.equal(cat.items[0].origin_status,'inferred');
assert(!JSON.stringify(cat).includes('PRIVATE'));
cat=I.buildCatalog(nodes,[I.fromImage({id:'s_hello',title:'Gen',url:`https://chatgpt.com/backend-api/estuary/content?id=${file}&sig=SECRET`})],details);
assert.equal(cat.items.length,1);assert.equal(cat.items[0].origin,'unknown');assert.equal(cat.items[0].origin_status,'conflicting');
assert(!JSON.stringify(cat).includes('SECRET'));
assert.equal(I.originFor({detail:I.fromDetail({use_case:'caas',metadata:{upload_source:'user'}})}).origin,'generated','transport must not override provenance');
assert.equal(I.originFor({detail:I.fromDetail({use_case:'codex',metadata:{upload_source:'user'}})}).origin,'unknown','Codex transport does not prove authorship');
assert.equal(I.originFor({detail:I.fromDetail({use_case:'gizmo',metadata:{upload_source:'user'}})}).origin,'unknown','project source does not prove authorship');
const link=I.sourceReference({id:'projectsource_1234567',file_id:file,name:'script.js',metadata:{knowledge_store_info:{source_kind:'library_file'}}},{id:'g-p-1234567890abcdef1234567890abcdef',name:'Logos'});
cat=I.linkCatalog(I.buildCatalog(nodes,[],details),[link]);
assert.equal(cat.items.length,1,'project placement does not duplicate file');
assert.equal(cat.items[0].contexts.includes('project_source'),true);
assert.equal(cat.summary.by_context.project_source,1);
assert.equal(cat.items[0].placements.find(p=>p.type==='project_source').ui_url,null,'do not invent project URLs');
assert(!JSON.stringify(cat).includes('PRIVATE')); 
const only=I.buildCatalog([], [I.fromImage({id:'s_galleryonly',title:'image',url:'https://chatgpt.com/backend-api/estuary/content?id=garbage'})]);
assert.equal(only.items.length,1);assert.equal(only.items[0].origin,'generated');assert.equal(only.items[0].file_id,null);
console.log('PASS: signed URL sanitization, conflict semantics, gallery ID not file ID, code suffix vs MIME, unknown gallery file');
